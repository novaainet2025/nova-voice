function cleanInline(value, maxLength = 260) {
  return String(value || '')
    .replace(/^['"]|['"]$/g, '')
    .replace(/[`*_<>]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, maxLength)
}

function listMarkdownFiles(directory) {
  if (!fs.existsSync(directory)) return []
  return fs.readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const fullPath = path.join(directory, entry.name)
      if (entry.isDirectory()) return listMarkdownFiles(fullPath)
      return entry.isFile() && entry.name.endsWith('.md') && !entry.name.includes('.bak') ? [fullPath] : []
    })
}

function inferDescription(body, command) {
  const frontmatter = body.match(/^---\s*\n([\s\S]*?)\n---/)
  const frontmatterDescription = frontmatter?.[1].match(/^description:\s*(.+)$/m)?.[1]
  if (frontmatterDescription) return cleanInline(frontmatterDescription)

  const lines = body.split(/\r?\n/)
  for (const line of lines.slice(0, 40)) {
    const normalized = line.replace(/^\s*#\s*/, '').trim()
    if (!normalized || normalized.startsWith('/') || /^(형식|사용법|예|\$ARGUMENTS)/.test(normalized)) continue
    if (/^(CLAUDE INSTRUCTION|generated by)/i.test(normalized)) continue
    return cleanInline(normalized)
  }
  return `${command} 명령`
}

function inferUsage(body, command) {
  const frontmatter = body.match(/^---\s*\n([\s\S]*?)\n---/)
  const hint = frontmatter?.[1].match(/^argument-hint:\s*(.+)$/m)?.[1]
  if (hint) return cleanInline(`${command} ${cleanInline(hint, 160)}`, 240)

  for (const line of body.split(/\r?\n/).slice(0, 100)) {
    const usage = line.match(/(?:형식|사용법)\s*:\s*(\/[A-Za-z0-9:_-]+[^\n]*)/i)?.[1]
    if (usage) return cleanInline(usage, 240)
  }
  const headingUsage = body.match(/^#\s*(\/[A-Za-z0-9:_-]+[^\n]*)/m)?.[1]
  return cleanInline(headingUsage || command, 240)
}

function commandAliases(command) {
  const name = command.replace(/^\//, '')
  const spaced = name.replace(/[-_:]+/g, ' ')
  return [...new Set([command, name, spaced])]
}

function parsePromptDefinitions() {
  const commands = []
  for (const root of definitionRoots) {
    for (const source of listMarkdownFiles(root.directory)) {
      const command = `/${path.basename(source, '.md')}`
      if (!/^\/[A-Za-z0-9][A-Za-z0-9:_-]*$/.test(command)) continue
      const body = fs.readFileSync(source, 'utf8')
      commands.push({
        command,
        provider: root.provider,
        domain: command.startsWith('/nco-') ? 'nco'
          : command.startsWith('/inter-session') ? 'inter-session'
            : command === '/mp' ? 'meta-prompt'
              : 'provider',
        description: inferDescription(body, command),
        usage: inferUsage(body, command),
        aliases: commandAliases(command),
        kind: 'slash-command',
        source,
      })
    }
  }
  return commands.sort((left, right) => left.command.localeCompare(right.command) || left.provider.localeCompare(right.provider))
}

function parseCodexBuiltIns() {
  const source = codexBinaryCandidates.find((candidate) => fs.existsSync(candidate))
  if (!source) return []
  const binary = fs.readFileSync(source)
  return codexBuiltInDefinitions.flatMap(([command, description]) => {
    if (!binary.includes(Buffer.from(command))) return []
    return [{
      command,
      provider: 'codex',
      domain: 'codex-built-in',
      description,
      usage: command === '/goal' ? '/goal <목표>' : command,
      aliases: commandAliases(command),
      kind: 'slash-command',
      source,
    }]
  })
}

function parseNovaUseCommands() {
  const source = path.join(homeDir, 'project', 'nova-use', 'src', 'renderer', 'components', 'browser', 'BrowserControlPanel.tsx')
  if (!fs.existsSync(source)) return []
  const body = fs.readFileSync(source, 'utf8')
  const commands = []
  const pattern = /\{\s*cmd:\s*'([^']+)'\s*,\s*desc:\s*'([^']+)'\s*,\s*template:\s*'([^']*)'/g
  for (const match of body.matchAll(pattern)) {
    if (!match[1].startsWith('/')) continue
    const command = match[1]
    commands.push({
      command,
      provider: 'nova-use',
      domain: 'nova-use-browser',
      description: cleanInline(match[2]),
      usage: cleanInline(`${command} ${match[3].replace(command, '').trim()}`),
      aliases: commandAliases(command),
      kind: 'slash-command',
      source,
    })
  }
  return commands
}

function parseNovaAxTools() {
  const source = path.join(homeDir, 'project', 'nova-ax', 'src', 'mcp', 'server.ts')
  if (!fs.existsSync(source)) return []
  const body = fs.readFileSync(source, 'utf8')
  const tools = []
  const pattern = /name:\s*'((?:ax_)[A-Za-z0-9_]+)'\s*,\s*\n\s*description:\s*'([^']+)'/g
  for (const match of body.matchAll(pattern)) {
    tools.push({ name: match[1], description: cleanInline(match[2]), kind: 'mcp-tool', source })
  }
  return tools.sort((left, right) => left.name.localeCompare(right.name))
}

function dedupeCommands(commands) {
  const seen = new Set()
  return commands.filter((entry) => {
    const key = `${entry.provider}:${entry.command}`
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
}

function markdownTable(entries) {
  return [
    '| 명령 | 사용법 | 설명 | 원본 |',
    '|---|---|---|---|',
    ...entries.map((entry) => `| \`${entry.command}\` | \`${entry.usage.replace(/\|/g, '\\|')}\` | ${entry.description.replace(/\|/g, '\\|')} | \`${entry.source}\` |`),
  ].join('\n')
}

